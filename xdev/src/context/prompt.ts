// 上下文压缩提示词

/**
 * 压缩提示词
 */
export const COMPACT_PROMPT = `# 对话压缩任务

你是一个对话压缩专家，负责将长对话压缩为简洁的摘要。

## 压缩原则

1. **保留关键信息**
   - 用户的原始请求和目标
   - 关键决策和选择
   - 重要发现和结论
   - 未完成的任务

2. **可省略内容**
   - 详细的工具调用过程
   - 重复的确认信息
   - 错误修复的中间步骤（保留最终解决方案）
   - 冗长的代码输出（只保留关键部分）

3. **结构清晰**
   - 使用列表和标题组织
   - 保持逻辑连贯
   - 突出重点

## 输出格式

使用 Markdown 格式，包含以下部分：

### 用户目标
[用户想要完成什么]

### 已完成
- [已完成的任务1]
- [已完成的任务2]

### 关键决策
- [决策1]
- [决策2]

### 进行中
[当前正在做的事情]

### 注意事项
[需要记住的重要信息]

## 限制
- 控制在 500 tokens 以内
- 使用简洁的语言
- 不要添加新信息`;

/**
 * 部分压缩提示词（用于增量压缩）
 */
export const PARTIAL_COMPACT_PROMPT = `# 增量压缩任务

请将以下新增的对话内容压缩为简洁的摘要，与之前的摘要合并。

## 输入
- 之前的摘要
- 新增的对话

## 输出
- 更新后的完整摘要

## 要求
- 保持格式一致
- 只添加新的关键信息
- 移除已过时的内容`;

/**
 * 获取压缩用户消息
 */
export function getCompactUserMessage(
  previousSummary: string | null,
  newContent: string
): string {
  if (previousSummary) {
    return `## 之前的摘要
${previousSummary}

## 新增对话
${newContent}

请合并生成更新后的摘要。`;
  }

  return `请将以下对话压缩为摘要：

${newContent}`;
}
